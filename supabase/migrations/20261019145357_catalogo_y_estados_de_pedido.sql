-- ===================== Catálogo =====================
create table public.settings (
  id int primary key default 1 check (id = 1),
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table public.categories (
  name text primary key check (char_length(name) between 1 and 60),
  icon text not null default 'package' check (char_length(icon) <= 40),
  orden int not null default 0
);

create table public.products (
  id bigint generated by default as identity primary key,
  nombre text not null check (char_length(nombre) between 1 and 200),
  cat text not null references public.categories(name) on update cascade on delete restrict,
  precio numeric(12,2) not null default 0 check (precio >= 0),
  stock int not null default 0 check (stock >= 0),
  vendidos int not null default 0 check (vendidos >= 0),
  oferta boolean not null default false,
  oculto boolean not null default false,
  nuevo date not null default current_date,
  descripcion text check (char_length(descripcion) <= 2000),
  img text check (char_length(img) <= 1000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index products_cat_idx on public.products(cat);

alter table public.settings enable row level security;
alter table public.categories enable row level security;
alter table public.products enable row level security;

create policy "Todos leen la configuración" on public.settings for select to anon, authenticated using (true);
create policy "Admin edita la configuración" on public.settings for update to authenticated
  using ((select private.is_admin())) with check ((select private.is_admin()));

create policy "Todos leen categorías" on public.categories for select to anon, authenticated using (true);
create policy "Admin crea categorías" on public.categories for insert to authenticated with check ((select private.is_admin()));
create policy "Admin edita categorías" on public.categories for update to authenticated using ((select private.is_admin())) with check ((select private.is_admin()));
create policy "Admin borra categorías" on public.categories for delete to authenticated using ((select private.is_admin()));

create policy "Todos leen productos visibles; admin todos" on public.products for select to anon, authenticated
  using (not oculto or (select private.is_admin()));
create policy "Admin crea productos" on public.products for insert to authenticated with check ((select private.is_admin()));
create policy "Admin edita productos" on public.products for update to authenticated using ((select private.is_admin())) with check ((select private.is_admin()));
create policy "Admin borra productos" on public.products for delete to authenticated using ((select private.is_admin()));

revoke all on public.settings, public.categories, public.products from anon;
grant select on public.settings, public.categories, public.products to anon;
grant select, insert, update, delete on public.categories, public.products to authenticated;
grant select, update on public.settings to authenticated;

